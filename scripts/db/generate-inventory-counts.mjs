#!/usr/bin/env node
/**
 * Regenerates scripts/db/inventory-counts.sql from prisma/schema (*.prisma @@map)
 * plus archived tables (schema archive).
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const schemaDir = path.join(ROOT, 'prisma/schema');
const outPath = path.join(ROOT, 'scripts/db/inventory-counts.sql');

const ARCHIVE_TABLES = [
  'compras_ordenes_legacy',
  'compras_orden_items',
  'compras_orden_documentos',
  'compras_orden_historial',
  'compras_orden_sequences',
];

function collectTables() {
  const publicTables = new Set();
  for (const file of fs.readdirSync(schemaDir).filter((f) => f.endsWith('.prisma') && f !== '91-archive.prisma')) {
    const content = fs.readFileSync(path.join(schemaDir, file), 'utf8');
    for (const block of content.matchAll(/^model [\s\S]*?^}/gm)) {
      if (block[0].includes('@@schema("archive")')) continue;
      const map = block[0].match(/@@map\("([^"]+)"\)/);
      if (map) publicTables.add(map[1]);
    }
  }
  return [
    ...[...publicTables].sort().map((tabla) => ({ schema: 'public', tabla })),
    ...ARCHIVE_TABLES.map((tabla) => ({ schema: 'archive', tabla })),
  ];
}

function countExpr(schema, tabla) {
  return `CASE WHEN to_regclass(format('%I.%I', '${schema}', '${tabla}')) IS NULL THEN NULL
        ELSE (xpath('/row/c/text()', query_to_xml(format('SELECT count(*) AS c FROM %I.%I', '${schema}', '${tabla}'), false, true, '')))[1]::text::bigint END`;
}

const rows = collectTables();
const selects = rows.map(
  ({ schema, tabla }) =>
    `SELECT '${tabla}' AS table_name, '${schema}' AS table_schema, ${countExpr(schema, tabla)} AS row_count`,
);

const sql = `-- Row counts (read-only). Missing tables → NULL (never fails).
-- Generated by: node scripts/db/generate-inventory-counts.mjs

WITH tables(schema_name, table_name) AS (
  VALUES
${rows.map(({ schema, tabla }) => `    ('${schema}', '${tabla}')`).join(',\n')}
)
SELECT t.table_name,
       t.schema_name AS table_schema,
       CASE WHEN to_regclass(format('%I.%I', t.schema_name, t.table_name)) IS NULL THEN NULL
            ELSE (xpath('/row/c/text()', query_to_xml(
              format('SELECT count(*) AS c FROM %I.%I', t.schema_name, t.table_name),
              false, true, ''
            )))[1]::text::bigint END AS row_count
FROM tables t
ORDER BY t.schema_name, t.table_name;
`;

fs.writeFileSync(outPath, sql);
console.log(`Wrote ${outPath} (${rows.length} tables)`);
